package com.xiaofeiwu.grandwitch;

/** The four of her: each deceives in its own way, and is met in its own. */
public enum WitchKind {
    /** The girl with a basket: gives a cake to whoever comes to her (and goes to the children first). What the cake is, is not decided till it is eaten. */
    GIFT,
    /** The old woman: sells potions for emeralds. All look to be good ones; some are not. */
    POTION,
    /** The trader: gives a good thing, which is cursed: carried long enough, it makes a mouse of the one who has it. */
    CURSE,
    /** The nanny: gathers the children of the village and leads them away, to her house, and makes mice of them there. */
    NANNY
}
